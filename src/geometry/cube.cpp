#include "geometry/cube.h"

MeshData createCube() {
    MeshData cube;

    cube.vertices = {
        // Back face (-Z)
        {{-0.5f, -0.5f, -0.5f}, {0, 0, 1}, {0, 0, -1}, {0, 0}},
        {{ 0.5f, -0.5f, -0.5f}, {1, 0, 0}, {0, 0, -1}, {1, 0}},
        {{ 0.5f,  0.5f, -0.5f}, {0, 0, 1}, {0, 0, -1}, {1, 1}},
        {{-0.5f,  0.5f, -0.5f}, {1, 0, 0}, {0, 0, -1}, {0, 1}},

        // Front face (+Z)
        {{-0.5f, -0.5f,  0.5f}, {1, 0, 0}, {0, 0, 1}, {0, 0}},
        {{ 0.5f, -0.5f,  0.5f}, {0, 0, 1}, {0, 0, 1}, {1, 0}},
        {{ 0.5f,  0.5f,  0.5f}, {1, 0, 0}, {0, 0, 1}, {1, 1}},
        {{-0.5f,  0.5f,  0.5f}, {0, 0, 1}, {0, 0, 1}, {0, 1}},

        // Left face (-X)
        {{-0.5f, -0.5f, -0.5f}, {0, 0, 1}, {-1, 0, 0}, {0, 0}},
        {{-0.5f, -0.5f,  0.5f}, {1, 0, 0}, {-1, 0, 0}, {1, 0}},
        {{-0.5f,  0.5f,  0.5f}, {0, 0, 1}, {-1, 0, 0}, {1, 1}},
        {{-0.5f,  0.5f, -0.5f}, {1, 0, 0}, {-1, 0, 0}, {0, 1}},

        // Right face (+X)
        {{ 0.5f, -0.5f,  0.5f}, {0, 0, 1}, {1, 0, 0}, {0, 0}},
        {{ 0.5f, -0.5f, -0.5f}, {1, 0, 0}, {1, 0, 0}, {1, 0}},
        {{ 0.5f,  0.5f, -0.5f}, {0, 0, 1}, {1, 0, 0}, {1, 1}},
        {{ 0.5f,  0.5f,  0.5f}, {1, 0, 0}, {1, 0, 0}, {0, 1}},

        // Top face (+Y)
        {{-0.5f,  0.5f,  0.5f}, {0, 0, 1}, {0, 1, 0}, {0, 0}},
        {{ 0.5f,  0.5f,  0.5f}, {1, 0, 0}, {0, 1, 0}, {1, 0}},
        {{ 0.5f,  0.5f, -0.5f}, {0, 0, 1}, {0, 1, 0}, {1, 1}},
        {{-0.5f,  0.5f, -0.5f}, {1, 0, 0}, {0, 1, 0}, {0, 1}},

        // Bottom face (-Y)
        {{-0.5f, -0.5f, -0.5f}, {0, 0, 1}, {0, -1, 0}, {0, 0}},
        {{ 0.5f, -0.5f, -0.5f}, {1, 0, 0}, {0, -1, 0}, {1, 0}},
        {{ 0.5f, -0.5f,  0.5f}, {0, 0, 1}, {0, -1, 0}, {1, 1}},
        {{-0.5f, -0.5f,  0.5f}, {1, 0, 0}, {0, -1, 0}, {0, 1}}
    };

    cube.indices = {
         0,  2,  1,   0,  3,  2,  // Back
         4,  5,  6,   4,  6,  7,  // Front
         8,  9, 10,   8, 10, 11,  // Left
        12, 13, 14,  12, 14, 15,  // Right
        16, 17, 18,  16, 18, 19,  // Top
        20, 21, 22,  20, 22, 23   // Bottom
    };

    return cube;
}
